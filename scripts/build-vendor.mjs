// Bundle the dev-only runtime library into vendor/, so the published plugin has no
// runtime dependencies and triggers no install scripts:
//   - ssh2 (CommonJS) -> vendor/ssh2.bundle.cjs, used by the SSH transport
// Re-run after upgrading the dependency: node scripts/build-vendor.mjs
// Pass --no-minify for a readable bundle when debugging the vendored code.
import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..')
const minify = !process.argv.includes('--no-minify')
const minifyNote = minify ? ' (minified; --no-minify for a readable bundle)' : ''
const ssh2Banner = `/*!
 * Bundled ssh2 (MIT) — https://github.com/mscdex/ssh2
 * Generated by scripts/build-vendor.mjs${minifyNote}; do not edit by hand.
 * The optional native accelerator (cpu-features) is intentionally not bundled:
 * ssh2 falls back to its pure-JavaScript implementation.
 */
`

const bundles = [
  {
    entry: path.join(root, 'vendor', 'ssh2-entry.mjs'),
    outfile: path.join(root, 'vendor', 'ssh2.bundle.cjs'),
    format: 'cjs',
    external: ['cpu-features', 'nan'],
    banner: ssh2Banner,
  },
]

const sizes = {}
for (const item of bundles) {
  await build({
    entryPoints: [item.entry],
    bundle: true,
    platform: 'node',
    format: /** @type {'cjs'} */ (item.format),
    target: 'node22',
    outfile: item.outfile,
    external: item.external,
    legalComments: 'inline',
    minify,
    banner: { js: item.banner },
    logLevel: 'info',
  })
  const text = await readFile(item.outfile, 'utf8')
  sizes[path.basename(item.outfile)] = (text.length / 1024).toFixed(0)
}

await writeFile(
  path.join(root, 'vendor', 'THIRD_PARTY_NOTICES.md'),
  `# Third-party notices

## ssh2

- Package: \`ssh2\` (MIT)
- Source: https://github.com/mscdex/ssh2
- Bundled file: \`vendor/ssh2.bundle.cjs\` (${sizes['ssh2.bundle.cjs']} KiB${minify ? ', minified' : ''})
- License text: see https://github.com/mscdex/ssh2/blob/master/LICENSE

The bundle excludes the optional native accelerator \`cpu-features\`; ssh2 uses its pure-JavaScript fallback then.
`,
  'utf8',
)
console.log(
  `[build-vendor] wrote ${Object.entries(sizes)
    .map(([name, kib]) => `${name} (${kib} KiB)`)
    .join(', ')} and THIRD_PARTY_NOTICES.md`,
)
