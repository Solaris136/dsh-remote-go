// Bundle the ssh2 dependency (devDependency) into a single ESM file under
// vendor/, so the published plugin has no runtime dependencies and triggers no
// install scripts. Re-run after upgrading ssh2: node scripts/build-vendor.mjs
import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..')
const outfile = path.join(root, 'vendor', 'ssh2.bundle.cjs')
const header = `/*!
 * Bundled ssh2 (MIT, CommonJS) — https://github.com/mscdex/ssh2
 * Generated by scripts/build-vendor.mjs; do not edit by hand.
 * The optional native accelerator (cpu-features) is intentionally not bundled:
 * ssh2 falls back to its pure-JavaScript implementation.
 */
`

await build({
  entryPoints: [path.join(root, 'vendor', 'ssh2-entry.mjs')],
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  outfile,
  external: ['cpu-features', 'nan'],
  legalComments: 'inline',
  banner: { js: header },
  logLevel: 'info',
})

const stats = await readFile(outfile, 'utf8')
await writeFile(
  path.join(root, 'vendor', 'THIRD_PARTY_NOTICES.md'),
  `# Third-party notices\n\n## ssh2\n\n- Package: \`ssh2\` (MIT)\n- Source: https://github.com/mscdex/ssh2\n- Bundled file: \`vendor/ssh2.bundle.mjs\` (${(stats.length / 1024).toFixed(0)} KiB)\n- License text: see https://github.com/mscdex/ssh2/blob/master/LICENSE\n\nThe bundle excludes the optional native accelerator \`cpu-features\`; ssh2 uses its pure-JavaScript fallback then.\n`,
  'utf8',
)
console.log(`[build-vendor] wrote ${path.relative(root, outfile)} (${(stats.length / 1024).toFixed(0)} KiB) and THIRD_PARTY_NOTICES.md`)
