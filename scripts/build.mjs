// Build the published JavaScript from the TypeScript sources, into `dist/`.
//
// tsc emits the whole program under `dist/` (`tsconfig.json`: `outDir: "./dist"`,
// `rootDir: "."`), so the source tree stays `.ts`-only: `index.ts` -> `dist/index.js`,
// `src/x.ts` -> `dist/src/x.js`, and the `connect/`, `proxy/`, `remote-web/`, `runtime/` and
// `node/` subdirectories keep their shape. The repository root and `src/` never receive an
// emitted `.js` again (the P8 stage of .agents/refactor/PLAN.md; decision I still governs the
// "artifacts are not committed" rule).
//
// The package still has to *ship* the published layout (`exports` addresses `./index.js`,
// DSH loads `client.js` and `src/**/*.js`), so `prepack` copies `dist/` to the package root
// (`scripts/stage-publish.mjs`) and `postpack` removes those copies again
// (`scripts/unstage-publish.mjs`). The tarball layout is therefore byte-identical to the one
// the plugin has always shipped, while the working tree has one generated directory.
//
// Clean before compiling: deleting or renaming a `.ts` leaves its old `.js` in `dist/`, and
// that stale artifact would be packed as a module that no longer exists. The cleanup removes
// `dist/` and, during the migration window, the legacy in-place twins (root `index.js`,
// `client.js`, `src/**/*.js`) that an older build left behind; `client/template.js`, `vendor/`,
// `types/` and `test/` are sources and are never touched. `dist/client.js` is regenerated by
// `scripts/build-client.mjs`, which `pnpm build` runs right after this script.
import { spawnSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { copyFile, mkdir, readdir, rm } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)))

// `--noEmit` makes this the type check the gate runs: it keeps the pinned compiler but must not
// delete the artifacts first, because a type check is not a build and the tree may be mid-phase.
const noEmit = process.argv.includes('--noEmit')

// Everything tsc emits lives here, and only here.
const DIST = 'dist'
// Legacy in-place output from before the `dist/` move. They are removed so a half-migrated
// checkout cannot pack a stale duplicate of the published layout.
const LEGACY_ROOT_FILES = ['index.js', 'client.js']
const LEGACY_DIRECTORIES = ['src']
// The ssh2 adapter imports the vendored bundle by a relative path (`../vendor/ssh2.bundle.cjs`).
// Inside `dist/` the emitted module sits one directory deeper, so the same specifier would point
// at `dist/vendor/` - mirroring the one runtime file there keeps the build output a complete,
// runnable package root. The published tarball never sees this copy: `src/**/*.js` is staged back
// to the package root, where `../vendor/` is the vendored file itself.
const VENDOR_FILES = ['vendor/ssh2.bundle.cjs']

/** Repository-relative paths under `dir` whose name matches `accept`. */
async function walk(dir, accept, out = []) {
  for (const entry of await readdir(path.join(root, dir), { withFileTypes: true }).catch(() => [])) {
    const rel = `${dir}/${entry.name}`
    if (entry.isDirectory()) await walk(rel, accept, out)
    else if (entry.isFile() && accept(entry.name)) out.push(rel)
  }
  return out
}

// The CLI pinned by this lockfile, never a global `tsc`/`npx`: a different TypeScript
// version reprints the emitted artifacts and would then read as drift on every machine
// except the one that ran the build.
const cli = path.join(root, 'node_modules', 'typescript', 'bin', 'tsc')

// Checked before the cleanup: a missing compiler must not be able to delete the artifacts it
// was supposed to regenerate.
if (!existsSync(cli)) {
  console.error(`[build] typescript is not installed (${path.relative(root, cli)}); run pnpm install`)
  process.exit(1)
}

if (!noEmit) {
  const stale = []
  for (const dir of LEGACY_DIRECTORIES) stale.push(...(await walk(dir, (name) => name.endsWith('.js'))))
  for (const file of LEGACY_ROOT_FILES) if (existsSync(path.join(root, file))) stale.push(file)
  for (const file of stale) await rm(path.join(root, file))
  // `dist/` is removed wholesale instead of file by file: it is generated output, so whatever
  // is in there was produced by a previous build of a tree that may no longer exist.
  await rm(path.join(root, DIST), { recursive: true, force: true })
  console.log(`[build] cleaned ${DIST}/ and ${stale.length} legacy in-place artifact(s) before compiling`)
}

const tscArgs = ['-p', path.join(root, 'tsconfig.json')]
if (noEmit) tscArgs.push('--noEmit')

const result = spawnSync(process.execPath, [cli, ...tscArgs], {
  cwd: root,
  // inherit: tsc's own diagnostics are the useful output, and a wrapper must not reshape them.
  stdio: 'inherit',
  // windowsHide keeps a console from flashing for every child the gates start.
  windowsHide: true,
})

if (result.error) {
  console.error(`[build] cannot start tsc: ${result.error.message}`)
  process.exit(1)
}
if (result.status !== 0) {
  console.error(`[build] tsc failed with exit code ${result.status ?? 'unknown'}`)
  process.exit(result.status === null ? 1 : result.status)
}

if (!noEmit) {
  for (const file of VENDOR_FILES) {
    const from = path.join(root, file)
    if (!existsSync(from)) {
      console.error(`[build] missing ${file}; the emitted adapter would not resolve its runtime import`)
      process.exit(1)
    }
    const to = path.join(root, DIST, file)
    await mkdir(path.dirname(to), { recursive: true })
    await copyFile(from, to)
  }
}
console.log(
  noEmit
    ? '[build] OK: tsc type-checked the sources (no emit)'
    : `[build] OK: tsc emitted the published layout under ${DIST}/ (with ${VENDOR_FILES.length} mirrored vendor file(s))`,
)
